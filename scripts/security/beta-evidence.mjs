#!/usr/bin/env node
/**
 * BETA-076 (Issue #1983) — beta security evidence capture.
 *
 * Produces a redacted, reproducible evidence block (Markdown) describing the
 * toolchain, application/contract versions, and deployment manifest identifiers
 * that the beta verification checklist records at verification time.
 *
 * Redaction policy (enforced here by construction):
 *   - Environment variable VALUES are never read or printed; only their names
 *     are listed as required placeholders.
 *   - Any 32-char lowercase-hex string (a real Cloudflare resource ID shape)
 *     found in committed manifests aborts the run with a non-zero exit code.
 *
 * Usage:
 *   node scripts/security/beta-evidence.mjs   # or: bun scripts/security/beta-evidence.mjs
 */

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

function read(relativePath) {
  return readFileSync(path.join(repoRoot, relativePath), "utf8");
}

function safeCommand(command, args) {
  try {
    return execFileSync(command, args, { encoding: "utf8", cwd: repoRoot }).trim();
  } catch {
    return "unavailable";
  }
}

function fail(message) {
  console.error(`[beta-evidence] REFUSING TO EMIT EVIDENCE: ${message}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Guard: real resource IDs must never be committed (SC-24 / TM-B14).
// ---------------------------------------------------------------------------

const REAL_ID_PATTERN = /[0-9a-f]{32}/;

for (const manifest of ["wrangler.jsonc"]) {
  const text = read(manifest);
  if (REAL_ID_PATTERN.test(text)) {
    fail(`${manifest} appears to contain a real Cloudflare resource ID.`);
  }
}

// ---------------------------------------------------------------------------
// Versions and identifiers.
// ---------------------------------------------------------------------------

const pkg = JSON.parse(read("package.json"));
let sorobanSdk = "unknown";
try {
  const cargo = read(path.join("contracts", "soroban", "Cargo.toml"));
  const match = cargo.match(/soroban-sdk\s*=\s*"([^"]+)"/);
  if (match) sorobanSdk = match[1];
} catch {
  // contracts tree absent — report unknown rather than failing evidence capture
}

const wranglerText = read("wrangler.jsonc");
const bindingNames = [
  ...new Set([...wranglerText.matchAll(/"binding"\s*:\s*"([^"]+)"/g)].map((m) => m[1])),
];
const placeholderTokens = [
  ...new Set([...wranglerText.matchAll(/\{[A-Z][A-Z0-9_]{2,}\}/g)].map((m) => m[0])),
];

const lines = [
  "<!-- Generated by `node scripts/security/beta-evidence.mjs` — paste into docs/security/beta-verification-checklist.md -->",
  "",
  "| Item | Value |",
  "| :--- | :---- |",
  `| Repository | ${pkg.name}${pkg.version ? `@${pkg.version}` : " (private, unversioned package)"} |`,
  `| Git commit | ${safeCommand("git", ["rev-parse", "HEAD"])} |`,
  `| Git branch | ${safeCommand("git", ["rev-parse", "--abbrev-ref", "HEAD"])} |`,
  `| Working tree | ${safeCommand("git", ["status", "--porcelain"]) === "" ? "clean" : "dirty (expected during verification)"} |`,
  `| Node.js | ${process.versions.node} |`,
  `| Bun | ${safeCommand("bun", ["--version"])} |`,
  `| Rustc / Cargo | ${safeCommand("rustc", ["--version"])} |`,
  `| soroban-sdk | ${sorobanSdk} |`,
  `| Contract crates | ${["policies", "postage", "receipts", "lifecycle"].join(", ")} |`,
  `| Worker entrypoint | src/server.ts (wrangler.jsonc main) |`,
  `| Bindings declared | ${bindingNames.join(", ") || "none found"} |`,
  `| Manifest ID placeholders | ${placeholderTokens.join(", ") || "none"} |`,
  "| Secret values | [REDACTED] — never read by this script |",
  "",
];

console.log(lines.join("\n"));
